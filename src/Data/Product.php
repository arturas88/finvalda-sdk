<?php

declare(strict_types=1);

namespace Finvalda\Data;

/**
 * Product entity DTO.
 */
final class Product extends Entity
{
    public function __construct(
        public readonly string $code,
        public readonly string $name,
        public readonly ?string $measureUnit = null,
        public readonly ?string $measureUnitName = null,
        public readonly ?float $measurementRatio = null,
        public readonly ?float $quantity = null,
        public readonly ?float $price1 = null,
        public readonly ?float $price2 = null,
        public readonly ?float $price3 = null,
        public readonly ?float $price4 = null,
        public readonly ?float $price5 = null,
        public readonly ?float $price6 = null,
        public readonly ?string $currency = null,
        public readonly ?float $buyPrice = null,
        public readonly ?string $buyCurrency = null,
        public readonly ?float $costPrice = null,
        public readonly ?float $markup = null,
        public readonly ?float $netWeight = null,
        public readonly ?float $grossWeight = null,
        public readonly ?float $volume = null,
        public readonly ?int $places = null,
        public readonly ?float $minQuantity = null,
        public readonly ?float $orderableQuantity = null,
        public readonly ?string $type = null,
        public readonly ?string $tag1 = null,
        public readonly ?string $tag2 = null,
        public readonly ?string $tag3 = null,
        public readonly ?string $tag4 = null,
        public readonly ?string $tag5 = null,
        public readonly ?string $tag6 = null,
        public readonly ?string $object1 = null,
        public readonly ?string $object2 = null,
        public readonly ?string $object3 = null,
        public readonly ?string $object4 = null,
        public readonly ?string $object5 = null,
        public readonly ?string $object6 = null,
        public readonly ?string $supplier1 = null,
        public readonly ?string $supplier2 = null,
        public readonly ?string $supplier3 = null,
        public readonly ?string $supplierCatalogCode1 = null,
        public readonly ?string $supplierCatalogCode2 = null,
        public readonly ?string $supplierCatalogCode3 = null,
        public readonly ?string $barcode = null,
        public readonly ?string $otherBarcodes = null,
        public readonly ?string $accountLink = null,
        public readonly ?string $taxCode = null,
        public readonly ?string $note = null,
        public readonly ?string $info = null,
        public readonly ?string $info1 = null,
        public readonly ?string $info2 = null,
        public readonly ?string $info3 = null,
        public readonly ?string $info4 = null,
        public readonly ?string $info5 = null,
        public readonly ?string $intrastatCode = null,
        public readonly ?string $url = null,
        public readonly ?string $productGroups = null,
        public readonly ?string $countryOfOrigin = null,
        public readonly ?bool $active = null,
        public readonly ?bool $isNew = null,
        public readonly ?string $createdAt = null,
        public readonly ?string $updatedAt = null,
        array $raw = [],
    ) {
        $this->raw = $raw;
    }

    public static function fromArray(array $data): static
    {
        return new self(
            code: self::stringValue($data, 'sKodas', 'kodas', 'preke') ?? '',
            name: self::stringValue($data, 'sPavadinimas', 'pavadinimas', 'prekes_pav') ?? '',
            measureUnit: self::stringValue($data, 'sMatavimoVnt', 'sMatVnt', 'mat_vieneto_pav', 'mato_vnt'),
            measureUnitName: self::stringValue($data, 'sMatVntPav', 'mat_vieneto_pav', 'mato_vnt_pav'),
            measurementRatio: self::floatValue($data, 'mat_santykis'),
            quantity: self::floatValue($data, 'dKiekis', 'kiekis'),
            price1: self::floatValue($data, 'dKaina1', 'pard_kaina_1', 'kaina1'),
            price2: self::floatValue($data, 'dKaina2', 'pard_kaina_2', 'kaina2'),
            price3: self::floatValue($data, 'dKaina3', 'pard_kaina_3', 'kaina3'),
            price4: self::floatValue($data, 'dKaina4', 'pard_kaina_4', 'kaina4'),
            price5: self::floatValue($data, 'dKaina5', 'pard_kaina_5', 'kaina5'),
            price6: self::floatValue($data, 'dKaina6', 'pard_kaina_6', 'kaina6'),
            currency: self::stringValue($data, 'sValiuta', 'pard_val', 'valiuta'),
            buyPrice: self::floatValue($data, 'dPirkimoKaina', 'pirk_kaina'),
            buyCurrency: self::stringValue($data, 'sPirkimoValiuta', 'pirk_valiuta'),
            costPrice: self::floatValue($data, 'dSavikaina', 'savikaina'),
            markup: self::floatValue($data, 'dAntkainis', 'antkainis'),
            netWeight: self::floatValue($data, 'dNeto', 'neto'),
            grossWeight: self::floatValue($data, 'dBruto', 'bruto'),
            volume: self::floatValue($data, 'dTuris', 'turis'),
            places: self::intValue($data, 'nVietuSkaicius', 'vietu_skaicius'),
            minQuantity: self::floatValue($data, 'nMinimalusKiekis'),
            orderableQuantity: self::floatValue($data, 'nUzsakomaPrekiu'),
            type: self::stringValue($data, 'sRusis', 'rusis'),
            tag1: self::stringValue($data, 'sPozymis1', 'pozymis_1', 'pozymis1'),
            tag2: self::stringValue($data, 'sPozymis2', 'pozymis_2', 'pozymis2'),
            tag3: self::stringValue($data, 'sPozymis3', 'pozymis_3', 'pozymis3'),
            tag4: self::stringValue($data, 'sPozymis4', 'pozymis_4', 'pozymis4'),
            tag5: self::stringValue($data, 'sPozymis5', 'pozymis_5', 'pozymis5'),
            tag6: self::stringValue($data, 'sPozymis6', 'pozymis_6', 'pozymis6'),
            object1: self::stringValue($data, 'sObjektas1', 'objektas1'),
            object2: self::stringValue($data, 'sObjektas2', 'objektas2'),
            object3: self::stringValue($data, 'sObjektas3', 'objektas3'),
            object4: self::stringValue($data, 'sObjektas4', 'objektas4'),
            object5: self::stringValue($data, 'sObjektas5', 'objektas5'),
            object6: self::stringValue($data, 'sObjektas6', 'objektas6'),
            supplier1: self::stringValue($data, 'sTiekejas1', 'tiekejas1'),
            supplier2: self::stringValue($data, 'sTiekejas2', 'tiekejas2'),
            supplier3: self::stringValue($data, 'sTiekejas3', 'tiekejas3'),
            supplierCatalogCode1: self::stringValue($data, 'sPreKodTiek1Kataloge'),
            supplierCatalogCode2: self::stringValue($data, 'sPreKodTiek2Kataloge'),
            supplierCatalogCode3: self::stringValue($data, 'sPreKodTiek3Kataloge'),
            barcode: self::stringValue($data, 'sBarKodas', 'sBruksnKodas', 'bar_kodas', 'barcode'),
            otherBarcodes: self::stringValue($data, 'sKitiBARKodai'),
            accountLink: self::stringValue($data, 'sRysysSuSask'),
            taxCode: self::stringValue($data, 'sMokestis'),
            note: self::stringValue($data, 'sPastaba', 'pastaba', 'pastabos'),
            info: self::stringValue($data, 'sInformacija', 'informacija'),
            info1: self::stringValue($data, 'sInfo1', 'info1'),
            info2: self::stringValue($data, 'sInfo2', 'info2'),
            info3: self::stringValue($data, 'sInfo3', 'info3'),
            info4: self::stringValue($data, 'sInfo4', 'info4'),
            info5: self::stringValue($data, 'sInfo5', 'info5'),
            intrastatCode: self::stringValue($data, 'sIntrastatKodas', 'intrastat_kodas'),
            url: self::stringValue($data, 'sUrl', 'url'),
            productGroups: self::stringValue($data, 'sPrekGrupes', 'prek_grupes'),
            countryOfOrigin: self::stringValue($data, 'sKilmesSalis', 'kilmes_salis'),
            active: self::boolValue($data, 'nAktyvi', 'aktyvi'),
            isNew: self::boolValue($data, 'bNauja', 'nauja'),
            createdAt: self::stringValue($data, 'tKurimoData', 'kurimo_data'),
            updatedAt: self::stringValue($data, 'tKoregavimoData', 'koregavimo_data'),
            raw: $data,
        );
    }

    public function toArray(): array
    {
        return array_filter([
            'sKodas' => $this->code,
            'sPavadinimas' => $this->name,
            'sMatavimoVnt' => $this->measureUnit,
            'dKaina1' => $this->price1,
            'dKaina2' => $this->price2,
            'dKaina3' => $this->price3,
            'dKaina4' => $this->price4,
            'dKaina5' => $this->price5,
            'dKaina6' => $this->price6,
            'sValiuta' => $this->currency,
            'dPirkimoKaina' => $this->buyPrice,
            'sPirkimoValiuta' => $this->buyCurrency,
            'dAntkainis' => $this->markup,
            'dNeto' => $this->netWeight,
            'dBruto' => $this->grossWeight,
            'dTuris' => $this->volume,
            'nVietuSkaicius' => $this->places,
            'nMinimalusKiekis' => $this->minQuantity,
            'nUzsakomaPrekiu' => $this->orderableQuantity,
            'sRusis' => $this->type,
            'sPozymis1' => $this->tag1,
            'sPozymis2' => $this->tag2,
            'sPozymis3' => $this->tag3,
            'sPozymis4' => $this->tag4,
            'sPozymis5' => $this->tag5,
            'sPozymis6' => $this->tag6,
            'sObjektas1' => $this->object1,
            'sObjektas2' => $this->object2,
            'sObjektas3' => $this->object3,
            'sObjektas4' => $this->object4,
            'sObjektas5' => $this->object5,
            'sObjektas6' => $this->object6,
            'sTiekejas1' => $this->supplier1,
            'sTiekejas2' => $this->supplier2,
            'sTiekejas3' => $this->supplier3,
            'sPreKodTiek1Kataloge' => $this->supplierCatalogCode1,
            'sPreKodTiek2Kataloge' => $this->supplierCatalogCode2,
            'sPreKodTiek3Kataloge' => $this->supplierCatalogCode3,
            'sBarKodas' => $this->barcode,
            'sKitiBARKodai' => $this->otherBarcodes,
            'sRysysSuSask' => $this->accountLink,
            'sMokestis' => $this->taxCode,
            'sPastaba' => $this->note,
            'sInformacija' => $this->info,
            'sInfo1' => $this->info1,
            'sInfo2' => $this->info2,
            'sInfo3' => $this->info3,
            'sInfo4' => $this->info4,
            'sInfo5' => $this->info5,
            'sIntrastatKodas' => $this->intrastatCode,
            'sUrl' => $this->url,
            'sPrekGrupes' => $this->productGroups,
            'sKilmesSalis' => $this->countryOfOrigin,
            'nAktyvi' => $this->active === null ? null : (int) $this->active,
            'bNauja' => $this->isNew === null ? null : (int) $this->isNew,
            'tKurimoData' => $this->createdAt,
            'tKoregavimoData' => $this->updatedAt,
        ], fn ($v) => $v !== null);
    }
}
