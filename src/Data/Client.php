<?php

declare(strict_types=1);

namespace Finvalda\Data;

/**
 * Client (customer/supplier) entity DTO.
 */
final class Client extends Entity
{
    public function __construct(
        public readonly string $code,
        public readonly string $name,
        public readonly ?string $name2 = null,
        public readonly ?string $address = null,
        public readonly ?string $address2 = null,
        public readonly ?string $city = null,
        public readonly ?string $postalCode = null,
        public readonly ?string $country = null,
        public readonly ?string $countryName = null,
        public readonly ?string $phone = null,
        public readonly ?string $fax = null,
        public readonly ?string $email = null,
        public readonly ?string $companyCode = null,
        public readonly ?string $vatCode = null,
        public readonly ?string $vatRateCode = null,
        public readonly ?string $bankCode = null,
        public readonly ?string $bankAccount = null,
        public readonly ?string $correspondentBankAccount = null,
        public readonly ?string $responsiblePerson = null,
        public readonly ?int $paymentDays = null,
        public readonly ?float $debt = null,
        public readonly ?float $currentDebt = null,
        public readonly ?float $creditLimit = null,
        public readonly ?float $taxPercent = null,
        public readonly ?string $paymentTermsCredit = null,
        public readonly ?string $paymentTermsDebit = null,
        public readonly ?float $penaltyCredit = null,
        public readonly ?float $penaltyDebit = null,
        public readonly ?int $debtDaysAllowed = null,
        public readonly ?float $maxOverdueDebt = null,
        public readonly ?string $type = null,
        public readonly ?int $typeCode = null,
        public readonly ?string $tag1 = null,
        public readonly ?string $tag2 = null,
        public readonly ?string $tag3 = null,
        public readonly ?string $object1 = null,
        public readonly ?string $object2 = null,
        public readonly ?string $object3 = null,
        public readonly ?string $object4 = null,
        public readonly ?string $object5 = null,
        public readonly ?string $object6 = null,
        public readonly ?string $notes = null,
        public readonly ?string $suggestedCurrency = null,
        public readonly ?bool $hasSubsidiary = null,
        public readonly ?float $additionalInfo = null,
        public readonly ?bool $isIndividual = null,
        public readonly ?bool $isVatPayer = null,
        public readonly ?bool $sendInvoices = null,
        public readonly ?string $debtAccount = null,
        public readonly ?string $creditAccount = null,
        public readonly ?bool $active = null,
        public readonly ?bool $isNew = null,
        public readonly ?string $createdAt = null,
        public readonly ?string $updatedAt = null,
        array $raw = [],
    ) {
        $this->raw = $raw;
    }

    public static function fromArray(array $data): static
    {
        return new self(
            code: self::stringValue($data, 'sKodas', 'kodas') ?? '',
            name: self::stringValue($data, 'sPavadinimas', 'pavadinimas') ?? '',
            name2: self::stringValue($data, 'sPavadinimas2', 'pavadinimas2'),
            address: self::stringValue($data, 'sAdresas', 'ardesas', 'adresas'),
            address2: self::stringValue($data, 'sAdresas2', 'adresas2'),
            city: self::stringValue($data, 'sMiestas', 'miestas'),
            postalCode: self::stringValue($data, 'sPastoKodas', 'pasto_kodas'),
            country: self::stringValue($data, 'sValstybeKodas', 'valstybe'),
            countryName: self::stringValue($data, 'sValstybe', 'sValstybePav', 'valstybe_pav'),
            phone: self::stringValue($data, 'sTelefonas', 'telefonas'),
            fax: self::stringValue($data, 'sFaksas', 'faksas'),
            email: self::stringValue($data, 'sEMail', 'sElPastas', 'el_pastas'),
            companyCode: self::stringValue($data, 'sImKodas', 'sImonesKodas', 'im_kodas'),
            vatCode: self::stringValue($data, 'sPvmMoketojoKod', 'sPVMKodas', 'pvm_moketojo_kodas'),
            vatRateCode: self::stringValue($data, 'sPvmMokKod', 'pvm_mok_kod'),
            bankCode: self::stringValue($data, 'sBankas', 'bankas'),
            bankAccount: self::stringValue($data, 'sBankoSaskaita', 'sBankoSask', 'banko_sask'),
            correspondentBankAccount: self::stringValue($data, 'sKorespSaskBank', 'korsp_sask_bank'),
            responsiblePerson: self::stringValue($data, 'sAtsakingasAsmuo', 'sAtskaitingasAsmuo', 'atskaitingas_asmuo'),
            paymentDays: self::intValue($data, 'nAtsiskaitytaPer', 'atsiskaityti_per'),
            debt: self::floatValue($data, 'dSkola', 'skola'),
            currentDebt: self::floatValue($data, 'dEinamojiSkola', 'einamoji_skola'),
            creditLimit: self::floatValue($data, 'nKreditas', 'kreditas'),
            taxPercent: self::floatValue($data, 'dMokestis', 'mokestis'),
            paymentTermsCredit: self::stringValue($data, 'sAtsiskaitymoTerminaiKred', 'atsiskaitymo_terminai_kred'),
            paymentTermsDebit: self::stringValue($data, 'sAtsiskaitymoTerminaiDebt', 'atsiskaitymo_terminai_debt'),
            penaltyCredit: self::floatValue($data, 'dDelspinigiaiKred', 'delspinigiai_kred'),
            penaltyDebit: self::floatValue($data, 'dDelspinigiaiDebt', 'delspinigiai_debt'),
            debtDaysAllowed: self::intValue($data, 'nSkolaGalimaPradelstiDien'),
            maxOverdueDebt: self::floatValue($data, 'nMaksPradlestosSkolosSum'),
            type: self::stringValue($data, 'sRusis', 'rusis'),
            typeCode: self::intValue($data, 'nTipas'),
            tag1: self::stringValue($data, 'sPozymis1', 'pozymis_1', 'pozymis1'),
            tag2: self::stringValue($data, 'sPozymis2', 'pozymis_2', 'pozymis2'),
            tag3: self::stringValue($data, 'sPozymis3', 'pozymis_3', 'pozymis3'),
            object1: self::stringValue($data, 'sObjektas1', 'objektas1'),
            object2: self::stringValue($data, 'sObjektas2', 'objektas2'),
            object3: self::stringValue($data, 'sObjektas3', 'objektas3'),
            object4: self::stringValue($data, 'sObjektas4', 'objektas4'),
            object5: self::stringValue($data, 'sObjektas5', 'objektas5'),
            object6: self::stringValue($data, 'sObjektas6', 'objektas6'),
            notes: self::stringValue($data, 'sPastabos', 'pastabos'),
            suggestedCurrency: self::stringValue($data, 'sPasiulomaValiuta', 'pasiuloma_valiuta'),
            hasSubsidiary: self::boolValue($data, 'sYraKlientoPadalinys', 'yra_padalinys'),
            additionalInfo: self::floatValue($data, 'dPapildomaInf', 'papildoma_inf'),
            isIndividual: self::boolValue($data, 'nFizinisAsmuo'),
            isVatPayer: self::boolValue($data, 'nPvmMokaPirkejas'),
            sendInvoices: self::boolValue($data, 'nSiustiFakturas'),
            debtAccount: self::stringValue($data, 'sDebtSask'),
            creditAccount: self::stringValue($data, 'sKredSask'),
            active: self::boolValue($data, 'nAktyvus', 'aktyvus'),
            isNew: self::boolValue($data, 'bNaujas', 'naujas'),
            createdAt: self::stringValue($data, 'tKurimoData', 'kurimo_data'),
            updatedAt: self::stringValue($data, 'tKoregavimoData', 'koregavimo_data'),
            raw: $data,
        );
    }

    public function toArray(): array
    {
        return array_filter([
            'sKodas' => $this->code,
            'sPavadinimas' => $this->name,
            'sPavadinimas2' => $this->name2,
            'sAdresas' => $this->address,
            'sAdresas2' => $this->address2,
            'sMiestas' => $this->city,
            'sPastoKodas' => $this->postalCode,
            'sValstybeKodas' => $this->country,
            'sValstybe' => $this->countryName,
            'sTelefonas' => $this->phone,
            'sFaksas' => $this->fax,
            'sEMail' => $this->email,
            'sImKodas' => $this->companyCode,
            'sPvmMoketojoKod' => $this->vatCode,
            'sPvmMokKod' => $this->vatRateCode,
            'sBankas' => $this->bankCode,
            'sBankoSaskaita' => $this->bankAccount,
            'sKorespSaskBank' => $this->correspondentBankAccount,
            'sAtsakingasAsmuo' => $this->responsiblePerson,
            'nAtsiskaitytaPer' => $this->paymentDays,
            'sAtsiskaitymoTerminaiKred' => $this->paymentTermsCredit,
            'sAtsiskaitymoTerminaiDebt' => $this->paymentTermsDebit,
            'dDelspinigiaiKred' => $this->penaltyCredit,
            'dDelspinigiaiDebt' => $this->penaltyDebit,
            'nSkolaGalimaPradelstiDien' => $this->debtDaysAllowed,
            'nMaksPradlestosSkolosSum' => $this->maxOverdueDebt,
            'nKreditas' => $this->creditLimit,
            'sRusis' => $this->type,
            'nTipas' => $this->typeCode,
            'sPozymis1' => $this->tag1,
            'sPozymis2' => $this->tag2,
            'sPozymis3' => $this->tag3,
            'sObjektas1' => $this->object1,
            'sObjektas2' => $this->object2,
            'sObjektas3' => $this->object3,
            'sObjektas4' => $this->object4,
            'sObjektas5' => $this->object5,
            'sObjektas6' => $this->object6,
            'sPastabos' => $this->notes,
            'sPasiulomaValiuta' => $this->suggestedCurrency,
            'sYraKlientoPadalinys' => $this->hasSubsidiary === null ? null : (int) $this->hasSubsidiary,
            'dPapildomaInf' => $this->additionalInfo,
            'nFizinisAsmuo' => $this->isIndividual === null ? null : (int) $this->isIndividual,
            'nPvmMokaPirkejas' => $this->isVatPayer === null ? null : (int) $this->isVatPayer,
            'nSiustiFakturas' => $this->sendInvoices === null ? null : (int) $this->sendInvoices,
            'sDebtSask' => $this->debtAccount,
            'sKredSask' => $this->creditAccount,
            'nAktyvus' => $this->active === null ? null : (int) $this->active,
            'bNaujas' => $this->isNew === null ? null : (int) $this->isNew,
            'tKurimoData' => $this->createdAt,
            'tKoregavimoData' => $this->updatedAt,
        ], fn ($v) => $v !== null);
    }
}
